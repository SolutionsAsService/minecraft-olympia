package dev.shadw.olympia.mobs;

import java.util.List;
import net.fabricmc.fabric.api.biome.v1.BiomeModifications;
import net.fabricmc.fabric.api.biome.v1.BiomeSelectors;
import net.fabricmc.fabric.api.object.builder.v1.entity.FabricEntityType;
import net.minecraft.core.Registry;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.Mob;
import net.minecraft.world.entity.MobCategory;
import net.minecraft.world.entity.SpawnPlacementTypes;
import net.minecraft.world.entity.monster.Monster;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.SpawnEggItem;
import net.minecraft.world.level.levelgen.Heightmap;

/** Every creature defined in mobs/*.json: types, spawn eggs, natural spawns. Generated by shadw-mod mob. */
public final class GeneratedMobs {
	public static final EntityType<Cyclops> CYCLOPS = register("cyclops", FabricEntityType.Builder.createMob(Cyclops::new, MobCategory.MONSTER,
			b -> b.spawnRestriction(SpawnPlacementTypes.ON_GROUND, Heightmap.Types.MOTION_BLOCKING_NO_LEAVES, Monster::checkMonsterSpawnRules)
					.defaultAttributes(Cyclops::createAttributes)).sized(0.6F, 1.95F).clientTrackingRange(8));
	public static final Item CYCLOPS_SPAWN_EGG = egg("cyclops_spawn_egg", CYCLOPS);
	public static final EntityType<Gorgon> GORGON = register("gorgon", FabricEntityType.Builder.createMob(Gorgon::new, MobCategory.MONSTER,
			b -> b.spawnRestriction(SpawnPlacementTypes.ON_GROUND, Heightmap.Types.MOTION_BLOCKING_NO_LEAVES, Monster::checkMonsterSpawnRules)
					.defaultAttributes(Gorgon::createAttributes)).sized(0.6F, 1.95F).clientTrackingRange(8));
	public static final Item GORGON_SPAWN_EGG = egg("gorgon_spawn_egg", GORGON);
	public static final EntityType<Hoplite> HOPLITE = register("hoplite", FabricEntityType.Builder.createMob(Hoplite::new, MobCategory.MONSTER,
			b -> b.spawnRestriction(SpawnPlacementTypes.ON_GROUND, Heightmap.Types.MOTION_BLOCKING_NO_LEAVES, Monster::checkMonsterSpawnRules)
					.defaultAttributes(Hoplite::createAttributes)).sized(0.6F, 1.95F).clientTrackingRange(8));
	public static final Item HOPLITE_SPAWN_EGG = egg("hoplite_spawn_egg", HOPLITE);
	public static final EntityType<Minotaur> MINOTAUR = register("minotaur", FabricEntityType.Builder.createMob(Minotaur::new, MobCategory.MONSTER,
			b -> b.spawnRestriction(SpawnPlacementTypes.ON_GROUND, Heightmap.Types.MOTION_BLOCKING_NO_LEAVES, Monster::checkMonsterSpawnRules)
					.defaultAttributes(Minotaur::createAttributes)).sized(0.6F, 1.95F).clientTrackingRange(12));
	public static final Item MINOTAUR_SPAWN_EGG = egg("minotaur_spawn_egg", MINOTAUR);
	public static final EntityType<Satyr> SATYR = register("satyr", FabricEntityType.Builder.createMob(Satyr::new, MobCategory.CREATURE,
			b -> b.spawnRestriction(SpawnPlacementTypes.ON_GROUND, Heightmap.Types.MOTION_BLOCKING_NO_LEAVES, Mob::checkMobSpawnRules)
					.defaultAttributes(Satyr::createAttributes)).sized(0.6F, 1.95F).clientTrackingRange(8));
	public static final Item SATYR_SPAWN_EGG = egg("satyr_spawn_egg", SATYR);

	/** The spawn eggs, for the creative tab. */
	public static final List<Item> EGGS = List.of(CYCLOPS_SPAWN_EGG, GORGON_SPAWN_EGG, HOPLITE_SPAWN_EGG, MINOTAUR_SPAWN_EGG, SATYR_SPAWN_EGG);

	private GeneratedMobs() {}

	private static <T extends net.minecraft.world.entity.Entity> EntityType<T> register(String path, EntityType.Builder<T> builder) {
		ResourceKey<EntityType<?>> key = ResourceKey.create(Registries.ENTITY_TYPE, ResourceLocation.fromNamespaceAndPath("olympia", path));
		return Registry.register(BuiltInRegistries.ENTITY_TYPE, key, builder.build(key));
	}

	private static Item egg(String path, EntityType<? extends Mob> type) {
		ResourceKey<Item> key = ResourceKey.create(Registries.ITEM, ResourceLocation.fromNamespaceAndPath("olympia", path));
		return Registry.register(BuiltInRegistries.ITEM, key, new SpawnEggItem(type, new Item.Properties().setId(key)));
	}

	/** Registers the natural spawns. Call from the main entrypoint. */
	public static void init() {
		BiomeModifications.addSpawn(BiomeSelectors.includeByKey(ResourceKey.create(Registries.BIOME, ResourceLocation.parse("minecraft:windswept_hills")), ResourceKey.create(Registries.BIOME, ResourceLocation.parse("minecraft:stony_peaks")), ResourceKey.create(Registries.BIOME, ResourceLocation.parse("minecraft:savanna_plateau"))), MobCategory.MONSTER, CYCLOPS, 3, 1, 1);
		BiomeModifications.addSpawn(BiomeSelectors.includeByKey(ResourceKey.create(Registries.BIOME, ResourceLocation.parse("minecraft:swamp")), ResourceKey.create(Registries.BIOME, ResourceLocation.parse("minecraft:mangrove_swamp"))), MobCategory.MONSTER, GORGON, 4, 1, 1);
		BiomeModifications.addSpawn(BiomeSelectors.includeByKey(ResourceKey.create(Registries.BIOME, ResourceLocation.parse("minecraft:plains")), ResourceKey.create(Registries.BIOME, ResourceLocation.parse("minecraft:meadow")), ResourceKey.create(Registries.BIOME, ResourceLocation.parse("minecraft:sunflower_plains"))), MobCategory.MONSTER, HOPLITE, 8, 1, 3);
		BiomeModifications.addSpawn(BiomeSelectors.includeByKey(ResourceKey.create(Registries.BIOME, ResourceLocation.parse("minecraft:forest")), ResourceKey.create(Registries.BIOME, ResourceLocation.parse("minecraft:meadow")), ResourceKey.create(Registries.BIOME, ResourceLocation.parse("minecraft:plains"))), MobCategory.CREATURE, SATYR, 6, 1, 3);
	}
}
